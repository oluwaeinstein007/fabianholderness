import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolveSiteUrl } from './resolve-site-url.mjs'

const siteUrl = resolveSiteUrl()
const publicDir = fileURLToPath(new URL('../public/', import.meta.url))

// Kept in sync by hand with src/articles.ts (slug + display date) — this
// plain .mjs script can't import that .ts module directly, so update both
// when an article is added, removed, or its date changes.
const ARTICLES = [
  { slug: 'innovative-strategies-for-outstanding-results', date: '06 Feb 2026' },
  { slug: 'business-thrives-global-initiatives', date: '06 Feb 2026' },
  { slug: 'redefining-company-goals', date: '06 Feb 2026' },
]

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

// "06 Feb 2026" -> "2026-02-06" — mirrors src/lib/seo.ts's toISODate.
function toISODate(displayDate) {
  const [day, month, year] = displayDate.split(' ')
  return `${year}-${String(MONTHS.indexOf(month) + 1).padStart(2, '0')}-${day.padStart(2, '0')}`
}

const buildDate = new Date().toISOString().slice(0, 10)

writeFileSync(
  `${publicDir}robots.txt`,
  `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`,
)

const urls = [
  { loc: `${siteUrl}/`, lastmod: buildDate, changefreq: 'weekly', priority: '1.0' },
  ...ARTICLES.map((a) => ({
    loc: `${siteUrl}/insights/${a.slug}`,
    lastmod: toISODate(a.date),
    changefreq: 'monthly',
    priority: '0.6',
  })),
]

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-files.mjs — update ARTICLES there
     when articles are added/removed/redated in src/articles.ts -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    (u) => `  <url>
    <loc>${u.loc}</loc>
    <lastmod>${u.lastmod}</lastmod>
    <changefreq>${u.changefreq}</changefreq>
    <priority>${u.priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`

writeFileSync(`${publicDir}sitemap.xml`, sitemap)

console.log(`[generate-seo-files] wrote robots.txt and sitemap.xml for ${siteUrl}`)
