import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolveSiteUrl } from './resolve-site-url.mjs'

const siteUrl = resolveSiteUrl()
const publicDir = fileURLToPath(new URL('../public/', import.meta.url))

const ARTICLE_SLUGS = [
  'innovative-strategies-for-outstanding-results',
  'business-thrives-global-initiatives',
  'redefining-company-goals',
]

writeFileSync(
  `${publicDir}robots.txt`,
  `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`,
)

const urls = [
  { loc: `${siteUrl}/`, changefreq: 'weekly', priority: '1.0' },
  ...ARTICLE_SLUGS.map((slug) => ({
    loc: `${siteUrl}/insights/${slug}`,
    changefreq: 'monthly',
    priority: '0.6',
  })),
]

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-files.mjs — update ARTICLE_SLUGS there
     when articles are added/removed in src/articles.ts -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    (u) => `  <url>
    <loc>${u.loc}</loc>
    <changefreq>${u.changefreq}</changefreq>
    <priority>${u.priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`

writeFileSync(`${publicDir}sitemap.xml`, sitemap)

console.log(`[generate-seo-files] wrote robots.txt and sitemap.xml for ${siteUrl}`)
